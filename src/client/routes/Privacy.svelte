<section class="container prose">
  <h1>Privacy</h1>
  <p>WatchTogether is designed to keep as little about you as possible, for as short a time as possible.</p>

  <h2>What we process</h2>
  <ul>
    <li>The <strong>display name</strong> you type when you start or join a room.</li>
    <li>The <strong>chat messages</strong> you send and the <strong>bingo squares</strong> you mark.</li>
  </ul>
  <p>
    This is shared only with the other people in your room. It's held in memory and temporary storage for that
    room only, and it's <strong>permanently deleted when the room closes</strong>, one hour after the episode
    ends. We keep no copies or backups.
  </p>

  <h2>What we don't do</h2>
  <ul>
    <li>No accounts, emails or passwords.</li>
    <li>No cookies, no analytics and no advertising trackers.</li>
    <li>We don't log your name, messages or room codes.</li>
  </ul>
  <p>
    Your browser keeps your room session and last-used name in <em>session storage</em> so a page refresh doesn't
    kick you out. It's cleared when you close the tab.
  </p>

  <h2>Infrastructure</h2>
  <p>
    The site runs on Cloudflare, which processes network data such as IP addresses to deliver and protect the
    service and to rate-limit abuse. Episode air times come from TVmaze. Your browser doesn't contact TVmaze
    directly.
  </p>

  <h2>Questions</h2>
  <p>
    Because rooms are deleted when they close, there's normally nothing left to access or erase. If you have a
    question, open an issue on the project's repository.
  </p>
